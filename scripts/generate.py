#!/usr/bin/env python3
"""Regenerate the committed continuous tables from the pinned Zenodo release."""
import argparse
import hashlib
import json
import math
from pathlib import Path, PurePosixPath
import tempfile
import urllib.request
import zipfile

ROOT = Path(__file__).resolve().parents[1]
VERSION = "9.0.0"
DOI = "10.5281/zenodo.24343380"
URL = "https://zenodo.org/records/24343380/files/ScientificColourMaps9.zip?download=1"
MD5 = "316c0cdbcec46d377f74c6c59523c7f0"
# naviaW existed in 8.0.1 but has no continuous table in the pinned 9.0.0 archive.
NAMES = sorted("acton bam bamO bamako batlow batlowK batlowW batlowO berlin bilbao broc brocO buda bukavu cork corkO davos delphi devon fes glasgow grayC hawaii imola lajolla lapaz lipari lisbon managua navia nuuk oleron oslo roma romaO ston tofino tokyo turku vanimo vik vikO".split())

def generate(archive):
    digest = hashlib.md5(usedforsecurity=False)
    with archive.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    if digest.hexdigest() != MD5:
        raise ValueError("Zenodo archive checksum mismatch")
    tables = {}
    licenses = []
    with zipfile.ZipFile(archive) as z:
        for member in z.infolist():
            p = PurePosixPath(member.filename)
            if p.name.lower() in {"license", "license.txt", "license.md", "licence", "licence.txt", "licence.md"} and not member.is_dir():
                data = z.read(member).decode("utf-8-sig")
                if "Permission is hereby granted, free of charge" in data and "Fabio Crameri" in data:
                    licenses.append((len(p.parts), member.filename, data))
            if p.suffix.lower() != ".txt" or p.stem != p.parent.name or p.stem not in NAMES:
                continue
            if p.stem in tables:
                raise ValueError(f"Duplicate table: {p.stem}")
            colors = []
            for line in z.read(member).decode("utf-8-sig").splitlines():
                if not line.strip():
                    continue
                values = [float(x) for x in line.split()]
                if len(values) != 3 or any(not math.isfinite(x) or not 0 <= x <= 1 for x in values):
                    raise ValueError(f"Invalid RGB row in {member.filename}: {line}")
                colors.append("#" + "".join(f"{math.floor(x * 255 + 0.5):02x}" for x in values))
            if len(colors) != 256:
                raise ValueError(f"{p.stem}: expected 256 rows, found {len(colors)}")
            tables[p.stem] = colors
    if set(tables) != set(NAMES):
        missing = sorted(set(NAMES) - set(tables))
        with zipfile.ZipFile(archive) as z:
            candidates = [name for name in z.namelist() if any(PurePosixPath(name).stem.lower().startswith(key.lower().rstrip("w")) for key in missing) and name.lower().endswith(".txt")]
        raise ValueError(f"Missing canonical tables: {missing}; candidate archive paths: {candidates[:100]}")
    if not licenses:
        raise ValueError("Cannot verify upstream MIT notice; review archive licensing")
    notice = sorted(licenses)[0][2].rstrip() + "\n"
    js = f"// Generated by scripts/generate.py from Scientific Colour Maps {VERSION}.\n// Fabio Crameri; https://doi.org/{DOI}\n"
    js += f'export const scientificColourMapsVersion = "{VERSION}";\n'
    js += "export const schemes = Object.freeze(\n  Object.fromEntries(\n    Object.entries({\n"
    for name in NAMES:
        js += f"      {name}: [\n" + "".join(f'        "{c}",\n' for c in tables[name]) + "      ],\n"
    js += "    }).map(([name, colors]) => [name, Object.freeze(colors)]),\n  ),\n);\nexport const paletteNames = Object.freeze(Object.keys(schemes));\n"
    types = "/** Generated canonical palette identifiers. */\nexport type ColormapName =\n" + "\n".join(f'  | "{name}"' for name in NAMES) + ";\n"
    return {
        "src/schemes.js": js,
        "src/palette-names.d.ts": types,
        "src/upstream-license.txt": notice,
    }

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=Path, help="Use a local copy of the pinned ZIP")
    parser.add_argument("--check", action="store_true", help="Fail if committed outputs differ")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        archive = args.archive or Path(tmp) / "ScientificColourMaps9.zip"
        if not args.archive:
            with urllib.request.urlopen(URL, timeout=120) as source, archive.open("wb") as target:
                while chunk := source.read(1024 * 1024):
                    target.write(chunk)
        outputs = generate(archive)
        for relative, content in outputs.items():
            path = ROOT / relative
            if args.check:
                if not path.exists() or path.read_bytes() != content.encode("utf-8"):
                    raise SystemExit(f"Generated file differs: {relative}")
            else:
                path.write_bytes(content.encode("utf-8"))

if __name__ == "__main__":
    main()
